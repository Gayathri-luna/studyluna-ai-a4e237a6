export type OpportunityKind = "internship" | "hackathon" | "competition" | "government";

export interface Opportunity {
  id: string;
  kind: OpportunityKind;
  title: string;
  organization: string;
  /** Short one-line description shown on the card. */
  summary: string;
  /** Who this is for — used by "Find My Opportunities" matching. */
  eligibility: string;
  /** Lowercase tags: branches, skills, levels. */
  tags: string[];
  /** e.g. "Remote", "Pan-India", "Bengaluru". */
  location: string;
  /** Deadline or window; placeholder when unknown. */
  deadline: string;
  stipend?: string;
  /** Direct application/registration URL — must open the exact destination. */
  applyUrl: string;
  /** Official organisation page (source of truth). */
  officialUrl: string;
}

